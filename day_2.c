#include <stdio.h>
int main (){



    // Integer - whole numbers
    int age = 15;
    
    // Float - decimal numbers
    float percentage = 85.5;
    
    // Char - single character
    char grade = 'A';
    
    printf("My age is %d\n", age);
    printf("My percentage is %f\n", percentage);
    printf("My grade is %c\n", grade);

    return 0;
}